"""Regenerate b2_hardware.json from results.json. Committed, not ad hoc.

WHY THIS FILE EXISTS. The B2 block summary -- including the paired comparison
that is the campaign's one clean positive result for CVQBoost -- was first
produced by a throwaway script. Every number in it reconciled against
results.json, but a figure that cannot be regenerated by committed code
contradicts the submission's own Appendix C claim that "every figure in this
submission regenerates from that repository". Found by internal review before
submission.

The bootstrap is seeded, so this is deterministic: running it on the same
results.json reproduces the same CI to the last digit.

    python experiments/src/summarize_b2.py [--check]

--check regenerates in memory and compares against the shipped artifact,
failing if they disagree. That is what the test uses.
"""
from __future__ import annotations

import argparse
import json
import statistics as st
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import store  # noqa: E402

RESULTS = Path(__file__).resolve().parents[1] / "results" / "results.json"
OUT = Path(__file__).resolve().parents[1] / "results" / "b2_hardware.json"

BOOT_SEED = 42
N_BOOT = 10_000

# The like-for-like comparator, named as a constant because getting it wrong is
# the failure that nearly shipped: B1's OVERALL mean (0.7351) averages in the
# weaker lg pool config and both temporal fits, and quoting it would have
# inflated the reported gain from +0.026 to +0.056. B2 is dct + stratified, so
# the comparator must be too.
COMPARATOR_CONFIG = "hw_b1_dct"
COMPARATOR_PROTOCOL = "stratified"


def _fidelity(rows: list[dict]) -> dict:
    """Weight cosine and objective gap against the classical solve.

    B2's agreement is markedly weaker than the schedule-2 arms', which is a
    caveat on the headline result rather than a footnote, so it belongs in the
    artifact the papers cite.
    """
    cos = [r["fidelity"]["weight_cosine"] for r in rows if r.get("fidelity")]
    gap = [r["fidelity"]["hw_objective_recomputed"] - r["fidelity"]["proxy_objective"]
           for r in rows if r.get("fidelity")]
    return {
        "weight_cosine_min": round(min(cos), 4),
        "weight_cosine_max": round(max(cos), 4),
        "weight_cosine_mean": round(st.mean(cos), 4),
        "objective_gap_mean": round(st.mean(gap), 1),
        "n": len(cos),
        "note": ("Hardware minus classical objective; positive means the device "
                 "found a worse minimum. Compare the schedule-2 B1 cells at "
                 "0.9747-0.9825 cosine."),
    }


def _degeneracy(rows: list[dict]) -> dict:
    """Mode share and distinct-score count, for the B.3 degeneracy paragraph."""
    ms = [r["metrics"]["mode_share"] for r in rows if r["metrics"].get("mode_share")]
    nd = [r["metrics"]["n_distinct_scores"] for r in rows
          if r["metrics"].get("n_distinct_scores")]
    out = {"tie_fraction_mean": round(
        st.mean(r["metrics"]["tie_fraction"] for r in rows), 4)}
    if ms:
        out["mode_share_mean"] = round(st.mean(ms), 4)
        out["mode_share_pct"] = round(100 * st.mean(ms), 1)
    if nd:
        out["n_distinct_scores_mean"] = round(st.mean(nd))
    return out


def build() -> dict:
    rows = [r for r in json.loads(RESULTS.read_text(encoding="utf-8"))["rows"]
            if isinstance(r, dict)]
    b2 = [r for r in rows if r.get("block") == "B2"]
    if not b2:
        raise SystemExit("no B2 rows in results.json")
    strat = [r for r in b2 if r["protocol"] == "stratified"]
    temp = [r for r in b2 if r["protocol"] == "temporal"][0]

    b2m = {r["seed"]: r["metrics"]["auprc"] for r in strat}
    b1m = {r["seed"]: r["metrics"]["auprc"] for r in rows
           if r.get("block") == "B1" and r.get("config") == COMPARATOR_CONFIG
           and r["protocol"] == COMPARATOR_PROTOCOL}
    seeds = sorted(set(b2m) & set(b1m))
    diffs = [b2m[s] - b1m[s] for s in seeds]

    rng = np.random.default_rng(BOOT_SEED)
    boot = [float(np.mean(rng.choice(diffs, len(diffs), replace=True)))
            for _ in range(N_BOOT)]
    lo, hi = (float(x) for x in np.percentile(boot, [2.5, 97.5]))

    ap = [r["metrics"]["auprc"] for r in strat]
    return {
        "note": ("B2: the ULB full config (top-17, schedule 3, 833 continuous "
                 "variables) on Dirac-3. Never runnable under A12's free-tier "
                 "ceiling; A21 retired that ceiling and the team lead authorised "
                 "the block on 2026-09-10."),
        "generator": "experiments/src/summarize_b2.py",
        "source": "experiments/results/results.json (rows with block == B2)",
        "evidence_tag": "HW",
        "n_fits": len(b2),
        "total_metered_seconds": sum(r["metered_seconds"] for r in b2),
        "n_variables": 833, "k": 17, "schedule": 3, "pair_build": "full",
        "stratified": {
            "n_seeds": len(ap),
            "auprc_mean": round(st.mean(ap), 4),
            # SAMPLE sd (ddof=1). gate_report.md prints the sample sd for this
            # same quantity, and at n=10 the population sd understates dispersion
            # by ~5%. Two artifacts disagreeing on one number is the defect class
            # this submission exists to avoid.
            "auprc_sd": round(st.stdev(ap), 4),
            "auprc_min": round(min(ap), 4), "auprc_max": round(max(ap), 4),
            "auc_roc_mean": round(st.mean(r["metrics"]["auc_roc"] for r in strat), 4),
            "tie_fraction_mean": round(
                st.mean(r["metrics"]["tie_fraction"] for r in strat), 4),
            "prevalence": strat[0]["metrics"]["prevalence"],
        },
        "temporal": {
            "auprc": round(temp["metrics"]["auprc"], 4),
            "auc_roc": round(temp["metrics"]["auc_roc"], 4),
        },
        "paired_vs_b1_dct": {
            "design": (f"B2 (833 vars) minus B1 {COMPARATOR_CONFIG} (78 vars) on "
                       "IDENTICAL seeds and protocol. The like-for-like comparator: "
                       "same pool family, same stratified protocol, differing only "
                       "in k (17 vs 13) and schedule (3 vs 2). B1's overall mean "
                       "mixes the weaker lg config and the temporal fits and is NOT "
                       "the right baseline."),
            "n_seeds": len(seeds),
            "per_seed": {str(s): round(b2m[s] - b1m[s], 4) for s in seeds},
            "b1_dct_mean": round(st.mean(b1m[s] for s in seeds), 4),
            "mean_difference": round(st.mean(diffs), 4),
            "sd_difference": round(st.stdev(diffs), 4),
            "ci95_bootstrap": [round(lo, 4), round(hi, 4)],
            "n_boot": N_BOOT,
            "boot_seed": BOOT_SEED,
            "seeds_favouring_b2": sum(1 for x in diffs if x > 0),
            "verdict": ("POSITIVE and consistent: 10 of 10 seeds favour the "
                        "833-variable configuration, mean +0.0256 AUPRC, 95% CI "
                        "excludes zero. Unpaired the effect hides inside a 0.028 "
                        "seed-to-seed sd; pairing cancels that variance. Lifting "
                        "the ceiling produces a real improvement."),
        },
        # Solver fidelity, STORED because B.3 quotes it and because its weakness
        # is the main caveat on the headline result. A figure that lives only in
        # prose is unchecked by construction (F44).
        "solver_fidelity": _fidelity(b2),
        "score_degeneracy": _degeneracy(strat),
        "limitation": ("tie_fraction averages 0.9224 across every seed, so this is "
                       "a STRUCTURAL property of the configuration, not a per-fit "
                       "artifact. B2's threshold-dependent figures are weak "
                       "evidence; its ranking metrics (AUPRC, AUC-ROC) are sound."),
        "rows": [{k: r.get(k) for k in ("seed", "protocol", "metered_seconds", "status")}
                 | {"auprc": round(r["metrics"]["auprc"], 4),
                    "auc_roc": round(r["metrics"]["auc_roc"], 4),
                    "tie_fraction": round(r["metrics"]["tie_fraction"], 4),
                    "evidence_tag": "HW"} for r in b2],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="compare against the shipped artifact instead of writing")
    args = ap.parse_args()
    built = build()
    if args.check:
        shipped = json.loads(OUT.read_text(encoding="utf-8"))
        # `note` and `generator` are prose; compare the evidence.
        keys = [k for k in built if k not in ("note", "generator", "source")]
        bad = [k for k in keys if built[k] != shipped.get(k)]
        if bad:
            print(f"MISMATCH in {bad}")
            return 1
        print("b2_hardware.json matches a fresh regeneration")
        return 0
    store.atomic_write_json(OUT, built)
    print(f"{OUT.name}: {built['n_fits']} fits, "
          f"{built['total_metered_seconds']:.0f}s, paired "
          f"{built['paired_vs_b1_dct']['mean_difference']:+.4f} "
          f"CI {built['paired_vs_b1_dct']['ci95_bootstrap']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
