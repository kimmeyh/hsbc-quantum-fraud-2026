"""Cost-based operating points and paired BCa intervals (Sprint 5 F26; A7 predictions).

Reads persisted predictions -- no refitting -- and reports what a fraud team
actually buys: fraud caught within a fixed daily review budget, and expected
cost under an asymmetric cost assumption stated openly as an assumption.

Also computes the per-seed paired BCa intervals the preregistration lists as
H1b support, which were OPEN in Sprint 4 because predictions were not stored.

Usage: python experiments/src/cost_analysis.py
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import metrics
import store

RESULTS_DIR = Path(__file__).resolve().parents[1] / "results"
OUT = RESULTS_DIR / "cost_report.md"

# Review capacities expressed as a fraction of scored transactions, which is how
# an alert budget actually binds (analyst headcount, not model properties).
ALERT_RATES = (0.0005, 0.001, 0.005)
# Cost assumption, STATED AS AN ASSUMPTION and swept: missed fraud vs false positive.
COST_RATIOS = (20.0, 50.0, 100.0)
N_SEEDS = 10


def _cells(rows):
    cells = defaultdict(list)
    for r in rows:
        if not store.prediction_path(r["config_hash"], r["seed"],
                                     r.get("protocol", "stratified")).exists():
            continue
        if r["arm"] == "cvqboost_proxy":
            key = (r["arm"], r.get("config"), r.get("pool_variant"))
        elif r["arm"] == "cvqboost_hw":
            if not (str(r.get("status", "ok")).startswith("ok")
                    and r.get("protocol") == "stratified"):
                continue
            key = (r["arm"], r.get("config"), None)
        else:
            key = (r["arm"], r.get("feature_set"), None)
        cells[key].append(r)
    return {k: v for k, v in cells.items() if len(v) >= N_SEEDS}


def _at_budget(y, p, rate):
    """Flag the top `rate` fraction by score: (caught, alerts, recall, precision)."""
    n_alerts = max(1, int(round(len(p) * rate)))
    idx = np.argsort(p)[::-1][:n_alerts]
    caught = int(y[idx].sum())
    total_fraud = int(y.sum())
    return caught, n_alerts, caught / max(total_fraud, 1), caught / n_alerts


def _name(key):
    return "/".join(str(x) for x in key if x is not None)


def main() -> int:
    rows = json.loads((RESULTS_DIR / "results.json").read_text())["rows"]
    cells = _cells(rows)
    lines = [
        "# Cost-Based Operating Points (generated by cost_analysis.py)", "",
        "Computed from PERSISTED predictions (amendment A7); no model was refit.", "",
        "## Assumptions, stated as assumptions", "",
        "- Review capacity is a fraction of scored transactions. A bank sets it from analyst "
        "headcount, so it is a policy input, not a property of the model.",
        "- The cost ratio (missed fraud versus false positive) is SWEPT over "
        f"{[int(c) for c in COST_RATIOS]} rather than fixed, because its true value is "
        "institution-specific.",
        "- Expected cost is reported RELATIVE to alerting nothing, so only differences between "
        "arms are interpreted.",
        "- ULB spans two days, so these are capacity-shaped comparisons, not a deployment forecast.",
        "",
        "## Fraud caught within a fixed review budget (mean over 10 seeds)", "",
        "| Arm / cell | " + " | ".join(f"recall @ {r:.2%}" for r in ALERT_RATES)
        + " | " + " | ".join(f"precision @ {r:.2%}" for r in ALERT_RATES) + " |",
        "|---" * (1 + 2 * len(ALERT_RATES)) + "|",
    ]

    preds = {}
    for key in sorted(cells, key=str):
        for r in cells[key]:
            p = store.load_predictions(r["config_hash"], r["seed"],
                                       r.get("protocol", "stratified"))
            if p is not None:
                preds[(key, r["seed"])] = p

    for key in sorted(cells, key=str):
        rec, prec = [], []
        for rate in ALERT_RATES:
            rr, pp = [], []
            for r in cells[key]:
                p = preds.get((key, r["seed"]))
                if p is None:
                    continue
                _, _, y_te, p_te = p
                _c, _n, recall, precision = _at_budget(np.asarray(y_te), np.asarray(p_te), rate)
                rr.append(recall)
                pp.append(precision)
            rec.append(float(np.mean(rr)) if rr else float("nan"))
            prec.append(float(np.mean(pp)) if pp else float("nan"))
        lines.append(f"| {_name(key)} | " + " | ".join(f"{v:.3f}" for v in rec)
                     + " | " + " | ".join(f"{v:.4f}" for v in prec) + " |")
    lines.append("")

    lines += [
        "## Expected cost per 1,000 transactions, relative to alerting nothing", "",
        "Lower is better. Cost = false_positives + ratio * missed_frauds, at the 0.1% budget.", "",
        "| Arm / cell | " + " | ".join(f"ratio {int(c)}" for c in COST_RATIOS) + " |",
        "|---" * (1 + len(COST_RATIOS)) + "|",
    ]
    rate = 0.001
    for key in sorted(cells, key=str):
        costs = []
        for ratio in COST_RATIOS:
            vals = []
            for r in cells[key]:
                p = preds.get((key, r["seed"]))
                if p is None:
                    continue
                _, _, y_te, p_te = p
                y_te = np.asarray(y_te)
                caught, n_alerts, _, _ = _at_budget(y_te, np.asarray(p_te), rate)
                fp = n_alerts - caught
                missed = int(y_te.sum()) - caught
                base = ratio * int(y_te.sum())
                vals.append((fp * 1.0 + ratio * missed - base) / len(y_te) * 1000.0)
            costs.append(float(np.mean(vals)) if vals else float("nan"))
        lines.append(f"| {_name(key)} | " + " | ".join(f"{v:+.2f}" for v in costs) + " |")
    lines.append("")

    lines += [
        "## Per-seed paired BCa intervals (prereg 9; closes the Sprint 4 OPEN item)", "",
        "Identical stratified resample indices on both arms' prediction vectors.", "",
        "Hardware predictions were not persisted in Sprint 4 (Dirac-3 weights; re-deriving "
        "them would cost metered seconds), so this runs on the EXACT PROXY of the same config. "
        "Sprint 4 measured hardware minus that proxy at -0.0010 AUPRC with the CI containing "
        "zero, so the substitution is supported by evidence rather than assumed.", "",
        "| Comparison | Seed | delta AP | BCa 95% CI | Excludes 0 |", "|---|---|---|---|---|",
    ]
    # Hardware predictions were never persisted (weights came from Dirac-3 and
    # re-deriving them costs metered seconds), so the per-seed paired BCa runs on
    # the EXACT PROXY of the same config -- which Sprint 4 measured as
    # indistinguishable from hardware (-0.0010, CI containing zero). Stated, not hidden.
    hw = next((k for k in cells if k[0] == "cvqboost_proxy" and k[1] == "free"
               and k[2] == "dct"), None)
    label = "CVQBoost exact proxy [SIM] - CatBoost matched13"
    cat = next((k for k in cells if k[0] == "catboost" and k[1] == "matched13"), None)
    n_excl = n_pairs = 0
    if hw and cat:
        hw_seed = {r["seed"]: r for r in cells[hw]}
        cat_seed = {r["seed"]: r for r in cells[cat]}
        for seed in sorted(set(hw_seed) & set(cat_seed)):
            a = preds.get((hw, seed))
            b = preds.get((cat, seed))
            if a is None or b is None:
                continue
            _, _, y_a, p_a = a
            _, _, _yb, p_b = b
            d = metrics.paired_delta_ci(np.asarray(y_a), np.asarray(p_a), np.asarray(p_b),
                                        metric="auprc", seed=seed)
            lo, hi = d["ci95"]
            excl = bool(lo > 0 or hi < 0)
            n_excl += excl
            n_pairs += 1
            lines.append(f"| {label} | {seed} | {d['diff']:+.4f} "
                         f"| [{lo:+.4f}, {hi:+.4f}] | {'yes' if excl else 'no'} |")
        lines += ["", f"{n_excl} of {n_pairs} per-seed intervals exclude zero. This is the "
                  "preregistered SUPPORT for H1b; the decision rule remains the across-seed "
                  "t-interval (prereg 3)."]
    else:
        lines.append("| (hardware or CatBoost matched-13 predictions unavailable) | | | | |")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"cost_report.md written: {len(cells)} cells with persisted predictions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
